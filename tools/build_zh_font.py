#!/usr/bin/env python3
"""Regenerate embedded UI glyphs: pip install fonttools; python tools/build_zh_font.py font.ttf.
Source: google/fonts ofl/notosanssc/NotoSansSC[wght].ttf, SIL OFL 1.1.
Only redistributable Noto glyphs are embedded; no Windows fonts are copied.
"""
import argparse
from io import BytesIO
from pathlib import Path
import hashlib
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools import subset

root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('font',type=Path);args=p.parse_args()
font=TTFont(args.font,recalcTimestamp=False)
if 'fvar' in font:font=instantiateVariableFont(font,{'wght':500},inplace=True)
text=''.join(p.read_text(encoding='utf-8-sig') for p in (root/'src/ui').glob('*.cpp'))
text+=(root/'src/ui/locales/zh-CN.json').read_text(encoding='utf-8')
# ASCII plus all localized characters, typographic marks, common units and symbols.
codepoints=set(range(0x20,0x100))|set(map(ord,text))|set(range(0x2000,0x2070))|{0x2212,0xfffd}
options=subset.Options();options.recalc_timestamp=False
sub=subset.Subsetter(options=options);sub.populate(unicodes=codepoints);sub.subset(font)
font['name'].setName('OFXR UI Chinese Subset',1,3,1,0x409)
font['name'].setName('OFXRUIChineseSubset-Medium',6,3,1,0x409)
buf=BytesIO();font.save(buf);data=buf.getvalue()
lines=['// Generated by tools/build_zh_font.py. Noto Sans SC subset, SIL OFL 1.1.',
       '// Source SHA-256: '+hashlib.sha256(args.font.read_bytes()).hexdigest(),
       'constexpr unsigned char kFont_zh[] = {']
lines += ['    '+','.join('0x%02x'%v for v in data[i:i+24])+',' for i in range(0,len(data),24)]
lines+=['};','']
(root/'src/ui/settings_font_zh.inc').write_text('\n'.join(lines),encoding='ascii')
print(f'Embedded {len(font.getBestCmap())} glyphs, {len(data)} bytes')
